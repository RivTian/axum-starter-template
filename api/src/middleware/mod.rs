//! 中间件。两件，都是**因为上游的默认行为会破坏信封契约**才自己写的。
//!
//! | 文件 | 替掉了什么 | 上游的默认行为错在哪 |
//! | --- | --- | --- |
//! | [`timeout`] | `tower_http::timeout::TimeoutLayer` | 超时回一个**空 body**，绕过信封；而且 `TimeoutLayer::new` 自 0.6.7 起 `#[deprecated]`，`-D warnings` 下直接红 |
//! | [`panic`] | `CatchPanicLayer::new()` 的默认响应 | 回的是 `text/plain` 的 `"Service panicked"`，同样绕过信封 |
//!
//! 这两条是**同一类缺陷**：上游中间件各自有一套"出错时回什么"的默认值，而它们都不知道
//! 本服务有信封这回事。一个服务里只要有一条路径回的不是信封，客户端就得写两套解析——
//! 那统一信封就白立了。
//!
//! 值得记一笔的是：这两处里，超时那条是实测 tower-http 时撞见的，panic 那条更隐蔽，要等
//! 到某个 handler 真的 panic 那天才暴露。它们长得一模一样，说明这不是运气问题，而是需要
//! 一条可复用的
//! 判据：**凡是能自己产出响应的第三方层，都要先问它产出的是不是信封。**

pub(crate) mod panic;
pub(crate) mod timeout;
