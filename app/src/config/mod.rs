//! 配置在装配层的那一半：选文件、读文件、解析、重载。
//!
//! 另一半（类型、展开、热度判别、校验、钳位、发布）在 `service_core::config`，全是纯函数。
//! 这个划分不是美学：`core` 因此不认识 TOML、不认识 `std::env`、不碰文件系统，于是整条
//! 管线可以在内存里被逐段验完。
//!
//! 启动与重载走两个入口，只共享一个不碰文件系统的 [`bootstrap::parse`]。共享得更多就会
//! 招来那个经典的 bug：删掉配置文件再 SIGHUP，进程静默重建缺省并报告"重载成功"。

pub(crate) mod bootstrap;
pub(crate) mod reload;
