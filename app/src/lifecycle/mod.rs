//! 生命周期编排：决定这一次运行何时停、怎么停、算不算停干净了。
//!
//! 三个子模块按"纯度"排，这个顺序不是审美：
//!
//! - [`stop`]：纯状态机。收到一次停止请求该做什么，全部取决于"这是第几次"和"现在几点"，
//!   而"现在几点"是**参数**。于是连按三次 Ctrl-C 这种场景可以在一个同步用例里跑完，
//!   不需要真的等 30 秒。
//! - [`report`]：纯数据 + 一个合取判据。退出码只由它算，别处一律不许直接 `exit`。
//! - `r#loop`：唯一有副作用的那个。它把上面两个的结论落到 supervisor、存储和 runtime 上。
//!
//! 这样切分的直接收益是：编排层的语义有自动化证据，而没有证据的部分被压缩到
//! `r#loop` 里那段固定序列——那段序列的每一步又各自在 `core` 里有用例。

pub(crate) mod r#loop;
pub(crate) mod report;
pub(crate) mod stop;
