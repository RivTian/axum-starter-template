#!/usr/bin/env bash
# 「生成即审计」那五项扫描的**判据本身**：三条正则、三份豁免清单、一个集合差。
#
# 这个文件不跑任何东西，只定义。它有两个消费者：
#
#   - `scripts/gen.sh`      —— 拿它们去扫真实的生成树
#   - `scripts/tooling-test.sh` —— 拿它们去扫**合成输入**，证明每一条真的能红
#
# ## 为什么要单独成文件
#
# 这些判据原本内联在 `gen.sh` 的主流程里。内联的代价是它们只能在"真的生成了一棵树"之后
# 才被执行，于是"这条正则拦不拦得住 X"这个问题只能靠读正则来回答——而读正则得出的结论
# 和它实际的行为是两回事，尤其在 BRE / ERE / 字符类边界这些地方。
#
# 搬出来之后，负向用例可以直接喂给它们一行合成文本。判据仍然只有一份定义：把它复制进
# 测试脚本是另一种写法，那种写法测的是复制品，而复制品和正品会漂移，且漂移的方向恰好是
# "测试永远绿"。

# ── 1. 未展开占位符（B-22）──────────────────────────────────────────────────
#
# 匹配**通用**形态 `{{ … }}`，而不是一张变量名清单。清单的失败模式是静默的：加第五个
# 变量时没人记得回来补，于是第五个变量泄漏进生成结果也不会有人知道。通用形态没有这种
# 失败模式——它不需要维护。
#
# 代价是 Rust 格式串里的 `{{`（转义出一个字面 `{`）会被一起匹配。这里用一份**逐条带理由**
# 的豁免清单处理，而不是把正则放松：放松正则等于把真泄漏和假阳性一起放过，而豁免清单
# 至少逼着加豁免的人写一句话说明它为什么不是泄漏。
AUDIT_PLACEHOLDER_RE='\{\{.*\}\}'

audit_placeholder_exempt() {  # $1 = 生成树内的相对路径
    case "$1" in
        core/src/config/expand.rs)   return 0 ;;  # 展开器自己要处理 `${{…}}`，模式串里就有它
        app/src/cli.rs)              return 0 ;;  # `--help` 里演示 `${VAR}` 语法的那段文本
        testkit/tests/discipline.rs) return 0 ;;  # 纪律扫描器的模式串里含 `{{`
        api/tests/contract.rs)       return 0 ;;  # 断言错误信封形状时用到格式串转义
        *)                           return 1 ;;
    esac
}

# ── 2. 历史标记（B-24）──────────────────────────────────────────────────────
#
# 拦的是模板自身开发过程的痕迹：里程碑编号、闸门编号、阶段编号。这些词对拿到生成结果的
# 人没有任何意义——他手上没有那张时间表。
#
# 正则是**限定形态**的，不是 `[Mm][0-9]+` 那种全面禁用。后者看起来更严，实际更弱：任何一个
# 叫 `m1` 的局部变量都会把门禁打红，于是它很快会被加上一长串豁免，再然后就没人看它了。
# 一个必须靠豁免清单才能用的检查，等于没有检查。
#
# 具体的收窄有两处，`scripts/tooling-test.sh` 逐条钉住：
#
#   - **大小写敏感**。`m1`、`m2` 这类局部变量名、参数名不匹配；只有大写 `M3` 才匹配。
#     B-24 点名的"参数 m1"因此不再误报。
#   - **词边界是 `[^A-Za-z0-9_]`**。`mem3`、`M3x`、`ARM64` 都不匹配。
#
# **已知且接受的假阳性**：`Apple M1` 这种"大写 M + 数字"的真实产品名会被匹配。当前交付面
# 里一个实例都没有，所以这里**不**预先铺一套逐行豁免机制——没有消费者的机制会先腐烂，
# 而这条检查真撞上那天的表现是一条指名道姓的红，修法和占位符那条一样：加一条带理由的
# 豁免。花一行修，不值得现在花一套。
#
# 阶段编号那一支写成**分支**而不是 `第[一二三四五六七八九]阶段`。门禁在 `LC_ALL=C` 下跑
# （见 `scripts/lib.sh` 顶部），C 下的 `[…]` 是字节集合：它要求 `第` 与 `阶段` 之间恰好
# 一个字节，而每个中文数字是三个字节，于是那条分支**一个真实输入都匹配不上**。它曾经就是
# 这么写的，写完到发现中间隔着好几个全绿的轮次——分支死了和检查通过长得一模一样。分支
# 形式逐个比对定长字节串，跟语言环境无关。
AUDIT_HISTORY_RE='(^|[^A-Za-z0-9_])(M[0-9]+|Phase[[:space:]]+[0-9]|GATE[[:space:]]+[0-9])([^A-Za-z0-9_]|$)|闸门|里程碑|第(一|二|三|四|五|六|七|八|九)阶段'

# ── 3. 未交付文件的引用（B-21）──────────────────────────────────────────────
#
# 清单是**算出来**的：模板树里有、生成树里没有的相对路径，就是"没随交付发布的文件"。
#
# 写死这份清单是行不通的——新增一个不发布的目录时没人会记得回来补，而那个目录的名字可以
# 大摇大摆地留在生成结果的文档里指向一个 404。算出来的清单不会漏。B-21 的原形态正是一条
# 手写正则，而它漏掉的恰好是那个仓库自己 README 里引用了两次的名字。
#
# 差集里还要再滤掉一类：**基名在生成树里真实存在**的根级文件。模板根上的 `Makefile` 和
# 生成结果里的 `Makefile` 是两份不同的文件，但拿 `Makefile` 这个词去扫，扫出来的全是生成
# 结果对它自己那份的正确自指。带目录分隔符的路径没有这个问题，一律保留——所以判据是
# "基名会不会撞车"，而不是"有没有斜杠"。后者会把 `cargo-generate.toml`、`Makefile.project`
# 这几个真正该查的根级名字一起漏掉。
audit_undelivered_paths() {  # $1 = 模板树文件清单，$2 = 生成树文件清单，$3 = 生成树基名清单
    while IFS= read -r path; do
        case "$path" in
            */*) printf '%s\n' "$path" ;;
            *)   grep -qxF -- "$path" "$3" || printf '%s\n' "$path" ;;
        esac
    done < <(comm -23 "$1" "$2")
}

# 最后一层过滤：**名字的含义独立于本仓库**的那几个，逐条带理由豁免。
#
# 判据是"读的人会不会扑空"。`rust-toolchain.toml` 是 Rust 生态的公共约定，一句"这份骨架
# 不带 rust-toolchain.toml"是在陈述一个他查得到、也验得了的事实，不会把他支到一个 404 上。
# 反过来 `Makefile.project` 只在生成之前存在，`hooks/post.rhai` 只在模板里存在——那两个
# 才是真扑空。
#
# 豁免的是**名字**不是文件：清单本身仍然是算出来的，新增一个不发布的目录照样会被逮住。
audit_undelivered_exempt() {  # $1 = 未交付相对路径
    case "$1" in
        rust-toolchain.toml) return 0 ;;  # Rust 生态公共约定，"本项目不钉工具链"要提它
        .gitattributes)      return 0 ;;  # git 公共约定，同上
        *)                   return 1 ;;
    esac
}

# ── 4. 模板自身的痕迹 ───────────────────────────────────────────────────────
#
# 判据是**语义**的：随交付发布的文件必须是写给这个项目的使用者看的。他手上没有设计稿，
# 所以「§5.5」「D24」「B-37」这类记号对他是死链接——比没有更糟，因为它们看起来像是能查的。
#
# 这一条没法用字符集扫（"禁止非 ASCII"与"注释用中文"的纪律直接冲突），只能靠一份关键词
# 黑名单。名单里每一类都对应一种真实写得出来的痕迹：
#
#   §N / DPn / Dn / [ABCX]-nn   设计稿的节号与纪律编号
#   设计稿 / 任务书 / 架构文档   设计期文档的指代
#   上一版 / 备份分支            模板自身的开发史
#   模板仓库 / 模板侧 / 模板作者  只有模板维护者才分得清的那一侧
#   axum-starter-template       模板仓库自己的名字
#
# 名单里**没有**光杆的「模板」：拿到这棵树的人刚刚亲手生成了它，"这个模板提供了 X"对他
# 是能解析的一句话。这条纪律拦的是他**无法解析**的引用，不是这个词本身。
AUDIT_TRACE_RE='§[0-9]|DP[0-9]|[^A-Za-z]D[0-9]|[ABCX]-[0-9][0-9]|设计稿|设计初稿|任务书|架构文档|备份分支|上一版|模板仓库|模板侧|模板作者|axum-starter-template'

# 唯一的豁免是**外部公开标准**的节号（`RFC 9110 §15.5.9`）：那是使用者查得到的东西，
# 正好是这条纪律要保护的反面。豁免写成一条"从命中行里滤掉"的正则，而不是写进
# `AUDIT_TRACE_RE`——后者要用负向环视，而 BSD 的 `grep -E` 没有。
AUDIT_TRACE_ALLOW_RE='RFC[[:space:]]+[0-9]+[[:space:]]*§'

# ── 5. 门禁的唯一入口 ───────────────────────────────────────────────────────
#
# 生成结果的门禁只有一个定义：它自己的 `make check`。
#
# 这一条扫的是**文档里的第二入口**，因为那才是它实际的失败形态：门禁本身没坏，坏的是
# README 里多了一句"另外还要跑一下 X"——那句话把一条检查移出了自动化，交给人的记性。
AUDIT_ENTRY_RE='另外还要跑|还需要单独跑|记得(手动)?跑|别忘了跑|单独执行一次|额外跑一遍'

# ── 6. 验收 ID 的两侧抽取（D54 / D55）───────────────────────────────────────
#
# 验收 ID **就是测试函数名**，不另发一套编号。
#
# X-01 记的是上一版的失败：55 个验收 ID 写在文档里，拿去 `.rs` 里搜**零命中**。那套编号
# 之所以能凭空长出来，是因为它和代码之间没有任何机械联系——`A-17` 这样的字符串在源码里
# 不存在，改名、删用例、甚至整节删掉都不会有人发现。再发一套编号只会把这件事重演一遍。
#
# 用函数名当 ID 换来一条硬性质：**改名就是改 ID**，两侧集合当场不等。代价是文档里的名字
# 很长，而且改一次用例名要同步改一行文档——这正是要的那个代价，它是这条纪律唯一的执行力
# 来源。
#
# ## 抽取必须按行锚定，不能用 `grep -c '#\[test\]'`
#
# 本仓库现在就有三处 `#[test]` 写在**文档注释的散文里**（`worker/tests/ticker.rs` 讲
# `clippy.toml` 那三条结构性豁免、`api/tests/contract.rs` 讲同一件事）。
#
# 这棵树上几种数法的结果，真实用例是 **264**：
#
#   `grep -c '#\[test\]'`                     192
#   `#[test]` / `#[tokio::test]` 两个字面量   255
#   `#[test` / `#[tokio::test` 前缀           267   （264 + 3 处散文）
#
# 多数的那三处本身不致命，致命的是方向：散文里多提一次 `#[test]`，文档侧就得凭空多出一
# 个不存在的 ID 才能让门禁变绿——于是这条门禁会**逼着人往文档里写假条目**。所以判据要求
# 属性**独占一行**（`^\s*#\[(?:tokio::)?test\b`），`///` 开头的行天然不满足。
#
# 属性与 `fn` 之间允许夹别的属性行（`#[should_panic]`、`#[ignore]`），但不允许夹代码或
# 空行——夹了就说明那个属性不是在修饰紧随其后的函数。
#
# ## 只认「行首是测试属性」，属性里写了什么一概不管
#
# 这里犯过一次错，值得留着：第一版写的是 `#\[(?:tokio::)?test\]` —— 要求属性**恰好**是那
# 两种字面量。于是 `#[tokio::test(start_paused = true)]` 和 `#[tokio::test(flavor = …)]`
# 全部抽不到，树上 **12** 条用例凭空消失，而且消失的正是关停编排与 ticker 那一批最吃重的
# 用例。两侧因此仍然相等（文档也是拿同一个抽取器建的），门禁全绿——这就是它要挡的那种绿。
#
# 教训是判据的**方向**：抽少了不会红，抽多了才会。所以宁可放宽武装条件（`test` 后面跟词
# 边界，属性参数不看），把「这一行是不是用例属性」的判断交给行首锚定，而不是交给对参数
# 形态的枚举——枚举永远会漏掉下一种写法。`\b` 顺带排掉 `#[test_case(…)]` 这类别的属性。
#
# ## 尾随的行注释要认，一行式不必认
#
# 探针（rustfmt 1.95.0，edition 2024）：`#[test] fn foo() {}` 会被拆成两行，而
# `#[test] // 理由` 的尾随注释**原样保留**。生成树上跑着 `cargo fmt --check`，所以一行式
# 在绿树里不可达，尾随注释式可达。
#
# ## 属性没在同一行闭合：大声红，不静静跳过
#
# 剩下的唯一一种抽不到的形态是手工把参数换行写的属性。rustfmt 不会把它折回去，所以它可达
# 但极罕见。既然「抽少了」是不会自己报警的那个方向，这里就不容它静默：检测到没闭合的测试
# 属性就带文件名和行号退非零，让调用方当场死掉。
audit_test_names() {  # 文件路径由参数给出；输出 `名字<TAB>路径`，每行一条
    perl -ne '
        if (/^\s*#\[(?:tokio::)?test\b/) {
            unless (/^\s*#\[(?:tokio::)?test(?:\s*\([^()]*\))?\]\s*(?:\/\/.*)?$/) {
                print STDERR "audit_test_names：$ARGV 第 $. 行的测试属性没在同一行闭合，\n"
                    . "   抽取器认不了它，而「认不了」在这条门禁里是**静默**的——那条用例会\n"
                    . "   从源码侧集合里消失，于是它永远不需要出现在 docs/acceptance.md 里。\n"
                    . "   把属性写回一行。\n   $_";
                $bad = 1;
            }
            $armed = 1;
        }
        elsif ($armed && /^\s*#\[/)                      { }          # 夹着的其它属性
        elsif ($armed && /^\s*(?:pub\s+)?(?:async\s+)?fn\s+([A-Za-z0-9_]+)/) {
            print "$1\t$ARGV\n"; $armed = 0;
        }
        elsif ($armed)                                   { $armed = 0 }  # 夹着代码或空行
        # 跨文件复位。少了这一句，上一个文件末尾若停在 armed 状态，下一个文件的第一行
        # 就会被算成它的用例——那条 ID 的出处会指向一个根本没有它的文件。
        $armed = 0 if eof;
        END { exit 3 if $bad }
    ' "$@"
}

# 文档侧只认一种形态：行首 `- ` 加反引号包住的名字。
#
# 写成"行首"而不是"行内任意位置"，是为了让散文里提到某条用例时**不会**被当成一个条目。
# 验收文档正文里会出现用例名（"这条由 `a_clean_shutdown_succeeds` 证明"），那是说明，不是
# 清单项；两者形态不同才分得开。
AUDIT_ACCEPTANCE_ID_RE='^- `[A-Za-z0-9_]+`'
