//! 让 `migrations/` 的改动能触发重新编译。
//!
//! `sqlx::migrate!()` 在**编译期**把 `migrations/` 整个读进二进制。cargo 默认只盯着
//! `.rs` 文件，所以没有这个文件时，改迁移目录不会触发重编——跑起来的仍是上一次编译进去的
//! 那一套，而且没有任何报错。那是一种"改了却没生效、还查不出来"的失败。
//!
//! 本模板实测过三种改动（增 / 改 / 删）：没有这个 `build.rs` 时新增一条迁移会被**静默忽略**
//! （已应用数纹丝不动）；有了它，三种改动都会强制重编。详见 `migrations/README.md`。
//!
//! 这个文件**不可删**。

fn main() {
    // `cargo::`（双冒号）是 1.77 起的指令语法；旧的 `cargo:` 单冒号形式仍可用，但会在新版
    // cargo 里被当作"未知指令"透传给链接器的那一类歧义来源。工作区 `rust-version` 是 1.95，
    // 用新语法没有兼容顾虑。
    println!("cargo::rerun-if-changed=migrations");
}
